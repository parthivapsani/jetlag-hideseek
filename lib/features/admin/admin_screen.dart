// Admin data providers
final _activeSessionsProvider =
    FutureProvider.autoDispose<List<GameSession>>((ref) async {
  final service = ref.watch(supabaseServiceProvider);
  if (service == null) return [];
  final raw = await service.getActiveSessions();
  return raw.map((e) => GameSession.fromJson(e)).toList();
});

final _allSessionsProvider =
    FutureProvider.autoDispose<List<GameSession>>((ref) async {
  final service = ref.watch(supabaseServiceProvider);
  if (service == null) return [];
  final raw = await service.getAllSessions();
  return raw.map((e) => GameSession.fromJson(e)).toList();
});

final _participantCountsProvider =
    FutureProvider.autoDispose<Map<String, int>>((ref) async {
  final service = ref.watch(supabaseServiceProvider);
  if (service == null) return {};
  final counts = await service.getSessionParticipantCounts();
  return {for (final c in counts) c['session_id'] as String: c['count'] as int};
});

final _featureRequestsProvider =
    FutureProvider.autoDispose<List<FeatureRequest>>((ref) async {
  final service = ref.watch(supabaseServiceProvider);
  if (service == null) return [];
  return service.getFeatureRequests();
});

final _gameAreasProvider =
    FutureProvider.autoDispose<List<GameArea>>((ref) async {
  final service = ref.watch(supabaseServiceProvider);
  if (service == null) return [];
  return service.getGameAreas();
});

final _recentEventsProvider =
    FutureProvider.autoDispose<List<GameEvent>>((ref) async {
  final client = ref.watch(supabaseClientProvider);
  if (client == null) return [];
  final response = await client
      .from('game_events')
      .select()
      .order('created_at', ascending: false)
      .limit(100);
  return (response as List).map((e) => GameEvent.fromJson({
    'id': e['id'],
    'sessionId': e['session_id'],
    'roundId': e['round_id'],
    'eventType': e['event_type'],
    'payload': e['payload'] ?? {},
    'createdAt': e['created_at'],
  })).toList();
});

class AdminScreen extends ConsumerStatefulWidget {
  const AdminScreen({super.key});

  @override
  ConsumerState<AdminScreen> createState() => _AdminScreenState();
}

class _AdminScreenState extends ConsumerState<AdminScreen> {
  bool _isCreating = false;
  String? _createdRoomCode;
  String? _selectedAreaId;
  final _locationController = TextEditingController();

  @override
  void dispose() {
    _locationController.dispose();
    super.dispose();
  }

  Future<void> _quickCreate(String query) async {
    final service = ref.read(supabaseServiceProvider);
    if (service == null) return;

    setState(() {
      _isCreating = true;
      _createdRoomCode = null;
    });

    try {
      // 1. Search Nominatim
      final nominatim = NominatimService();
      final places = await nominatim.search(query, limit: 1);
      nominatim.dispose();

      if (places.isEmpty || places.first.boundaryPolygon == null) {
        throw Exception('No boundary found for "$query". Try a more specific place name.');
      }

      final place = places.first;
      final polygon = place.toPolygonData();
      if (polygon == null) throw Exception('Could not parse boundary polygon');

      // 2. Create game area
      final area = GameArea(
        id: '', // will be generated by Supabase
        name: place.displayName.split(',').first,
        inclusionPolygons: [polygon],
        exclusionPolygons: [],
        centerLat: place.lat,
        centerLng: place.lng,
        defaultZoom: 13.0,
        createdBy: 'admin',
      );
      final savedArea = await service.createGameArea(area);

      // 3. Create session
      final session = await service.createSession(
        gameAreaId: savedArea.id,
        hidingPeriodSeconds: 3600,
        zoneRadiusMeters: 804.672,
        createdBy: 'admin',
      );

      setState(() {
        _createdRoomCode = session.roomCode;
        _isCreating = false;
      });
      _refresh();
    } catch (e) {
      setState(() => _isCreating = false);
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(content: Text(e.toString())),
        );
      }
    }
  }

  void _refresh() {
    ref.invalidate(_activeSessionsProvider);
    ref.invalidate(_allSessionsProvider);
    ref.invalidate(_participantCountsProvider);
    ref.invalidate(_featureRequestsProvider);
    ref.invalidate(_gameAreasProvider);
    ref.invalidate(_recentEventsProvider);
    ref.invalidate(apiUsageStatsProvider);
  }

  Future<void> _stopSession(String sessionId) async {
    final service = ref.read(supabaseServiceProvider);
    if (service == null) return;
    try {
      await service.stopSession(sessionId);
      _refresh();
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          const SnackBar(content: Text('Session stopped')),
        );
      }
    } catch (e) {
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(content: Text('Failed to stop session: $e')),
        );
      }
    }
  }

  Future<void> _createGame(String areaId) async {
    final service = ref.read(supabaseServiceProvider);
    if (service == null) return;
    setState(() => _isCreating = true);
    try {
      final session = await service.createSession(
        gameAreaId: areaId,
        hidingPeriodSeconds: 3600,
        zoneRadiusMeters: 804.672,
        createdBy: 'admin',
      );
      setState(() {
        _createdRoomCode = session.roomCode;
        _isCreating = false;
      });
      _refresh();
    } catch (e) {
      setState(() => _isCreating = false);
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(content: Text('Failed to create game: $e')),
        );
      }
    }
  }

  Future<void> _updateFeatureStatus(String id, String status) async {
    final service = ref.read(supabaseServiceProvider);
    if (service == null) return;
    try {
      await service.updateFeatureRequestStatus(id, status);
      ref.invalidate(_featureRequestsProvider);
    } catch (e) {
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(content: Text('Failed to update status: $e')),
        );
      }
    }
  }

  @override
  Widget build(BuildContext context) {
    final activeSessions = ref.watch(_activeSessionsProvider);
    final allSessions = ref.watch(_allSessionsProvider);
    final counts = ref.watch(_participantCountsProvider);
    final featureRequests = ref.watch(_featureRequestsProvider);
    final gameAreas = ref.watch(_gameAreasProvider);

    return Scaffold(
      appBar: AppBar(
        leading: IconButton(
          icon: const Icon(Icons.arrow_back),
          onPressed: () => context.go('/'),
        ),
        title: const Text('Jet Lag Admin'),
        actions: [
          IconButton(
            icon: const Icon(Icons.refresh),
            onPressed: _refresh,
          ),
        ],
      ),
      body: ListView(
        padding: const EdgeInsets.all(16),
        children: [
          // ======= Active Games =======
          _SectionHeader(title: 'Active Games', icon: Icons.play_circle_outline),
          const SizedBox(height: 12),
          activeSessions.when(
            loading: () => const _LoadingWidget(),
            error: (e, _) => _ErrorWidget(error: e.toString()),
            data: (sessions) {
              if (sessions.isEmpty) {
                return _EmptyWidget(message: 'No active games');
              }
              return Column(
                children: sessions.map((s) {
                  final playerCount = counts.maybeWhen(
                    data: (c) => c[s.id] ?? 0,
                    orElse: () => 0,
                  );
                  return Padding(
                    padding: const EdgeInsets.only(bottom: 12),
                    child: _SessionCard(
                      session: s,
                      participantCount: playerCount,
                      onSpectate: () => context.go('/game/${s.id}/spectator'),
                      onStop: () => _stopSession(s.id),
                    ),
                  );
                }).toList(),
              );
            },
          ),

          const SizedBox(height: 28),

          // ======= Create Game =======
          _SectionHeader(title: 'Create Game', icon: Icons.add_circle_outline),
          const SizedBox(height: 12),
          JetlagCard(
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.stretch,
              children: [
                // Quick create from location name
                Row(
                  children: [
                    Expanded(
                      child: TextField(
                        controller: _locationController,
                        decoration: const InputDecoration(
                          hintText: 'Type a location (e.g., Midtown Manhattan)',
                        ),
                        onSubmitted: (v) {
                          if (v.trim().isNotEmpty && !_isCreating) {
                            _quickCreate(v.trim());
                          }
                        },
                      ),
                    ),
                    const SizedBox(width: 12),
                    JetlagButton(
                      label: 'Create Game',
                      icon: Icons.bolt,
                      isLoading: _isCreating,
                      onPressed: _isCreating ? null : () {
                        final q = _locationController.text.trim();
                        if (q.isNotEmpty) _quickCreate(q);
                      },
                    ),
                  ],
                ),

                const SizedBox(height: 16),
                Center(
                  child: Text(
                    '\u2014 or \u2014',
                    style: TextStyle(color: context.textSecondary, fontSize: 13),
                  ),
                ),
                const SizedBox(height: 16),

                // Draw New Area button
                Center(
                  child: JetlagButton(
                    label: 'New Game Area + Game',
                    icon: Icons.map_outlined,
                    variant: JetlagButtonVariant.primary,
                    onPressed: () => context.push('/create-game'),
                  ),
                ),

                // If areas exist, also show quick create
                gameAreas.when(
                  loading: () => const SizedBox.shrink(),
                  error: (_, __) => const SizedBox.shrink(),
                  data: (areas) {
                    if (areas.isEmpty) {
                      return Padding(
                        padding: const EdgeInsets.only(top: 12),
                        child: Text(
                          'Draw a game area on the map to get started',
                          style: TextStyle(color: context.textSecondary, fontSize: 13),
                          textAlign: TextAlign.center,
                        ),
                      );
                    }
                    return Column(
                      children: [
                        const SizedBox(height: 16),
                        Divider(color: context.border),
                        const SizedBox(height: 16),
                        Text(
                          'Or use an existing area:',
                          style: TextStyle(color: context.textSecondary, fontSize: 13),
                        ),
                        const SizedBox(height: 12),
                        DropdownButtonFormField<String>(
                          value: _selectedAreaId ?? areas.first.id,
                          decoration: const InputDecoration(labelText: 'Game Area'),
                          items: areas.map((a) => DropdownMenuItem(
                            value: a.id,
                            child: Text(a.name),
                          )).toList(),
                          onChanged: (v) => setState(() => _selectedAreaId = v),
                        ),
                        const SizedBox(height: 12),
                        Center(
                          child: JetlagButton(
                            label: 'Create Game',
                            icon: Icons.add,
                            isLoading: _isCreating,
                            onPressed: _isCreating ? null : () {
                              final areaId = _selectedAreaId ?? areas.first.id;
                              _createGame(areaId);
                            },
                          ),
                        ),
                      ],
                    );
                  },
                ),

                // Show created game link
                if (_createdRoomCode != null) ...[
                  const SizedBox(height: 16),
                  JetlagCard(
                    borderColor: context.green,
                    child: Row(
                      children: [
                        Expanded(
                          child: Column(
                            crossAxisAlignment: CrossAxisAlignment.start,
                            children: [
                              Text('Game Created!',
                                style: Theme.of(context).textTheme.titleMedium?.copyWith(color: context.green)),
                              const SizedBox(height: 4),
                              SelectableText('jetlag.ratz.fyi/g/$_createdRoomCode',
                                style: Theme.of(context).textTheme.bodyLarge),
                            ],
                          ),
                        ),
                        IconButton(
                          icon: const Icon(Icons.copy, size: 18),
                          onPressed: () {
                            Clipboard.setData(ClipboardData(text: 'https://jetlag.ratz.fyi/g/$_createdRoomCode'));
                            ScaffoldMessenger.of(context).showSnackBar(
                              const SnackBar(content: Text('Link copied')),
                            );
                          },
                        ),
                      ],
                    ),
                  ),
                ],
              ],
            ),
          ),

          const SizedBox(height: 28),

          // ======= API Usage =======
          _SectionHeader(title: 'API Usage', icon: Icons.data_usage),
          const SizedBox(height: 12),
          _ApiUsageWidget(),

          const SizedBox(height: 28),

          // ======= Event Log =======
          _SectionHeader(title: 'Event Log', icon: Icons.list_alt),
          const SizedBox(height: 12),
          _EventLogSection(),

          const SizedBox(height: 28),

          // ======= Feature Requests =======
          _SectionHeader(title: 'Feature Requests', icon: Icons.lightbulb_outline),
          const SizedBox(height: 12),
          featureRequests.when(
            loading: () => const _LoadingWidget(),
            error: (e, _) => _ErrorWidget(error: e.toString()),
            data: (requests) {
              if (requests.isEmpty) {
                return _EmptyWidget(message: 'No feature requests');
              }
              return Column(
                children: requests.map((r) {
                  return Padding(
                    padding: const EdgeInsets.only(bottom: 12),
                    child: _FeatureRequestAdminCard(
                      request: r,
                      onStatusChange: (status) =>
                          _updateFeatureStatus(r.id, status),
                    ),
                  );
                }).toList(),
              );
            },
          ),

          const SizedBox(height: 28),

          // ======= Previous Games =======
          _SectionHeader(title: 'Previous Games', icon: Icons.history),
          const SizedBox(height: 12),
          allSessions.when(
            loading: () => const _LoadingWidget(),
            error: (e, _) => _ErrorWidget(error: e.toString()),
            data: (sessions) {
              final ended = sessions
                  .where((s) => s.status == SessionStatus.ended)
                  .toList();
              if (ended.isEmpty) {
                return _EmptyWidget(message: 'No previous games');
              }
              return Column(
                children: ended.map((s) {
                  final playerCount = counts.maybeWhen(
                    data: (c) => c[s.id] ?? 0,
                    orElse: () => 0,
                  );
                  return Padding(
                    padding: const EdgeInsets.only(bottom: 12),
                    child: _EndedSessionCard(
                      session: s,
                      participantCount: playerCount,
                    ),
                  );
                }).toList(),
              );
            },
          ),

          const SizedBox(height: 32),
        ],
      ),
    );
  }
}

